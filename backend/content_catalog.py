def generate_infinite_content_batch(
    page: int = 1,
    limit: int = 12,
    category: str = "all",
    decade: str = None,
    platform_filter: str = "all"
) -> List[Dict[str, Any]]:
    """
    Generate infinite stream of recommendations dynamically across YouTube, Facebook Watch, and 𝕏.
    Ensures that as seniors scroll, content NEVER runs out.
    """
    import urllib.parse
    
    platforms = ["youtube", "facebook", "x"]
    if platform_filter and platform_filter != "all":
        platforms = [platform_filter]
        
    candidates = INFINITE_CONTENT_BLUEPRINTS
    if category and category != "all":
        candidates = [b for b in candidates if b["category"] == category] or candidates
    if decade and decade != "all":
        candidates = [b for b in candidates if decade in b.get("decades", [])] or candidates

    results = []
    base_index = (page - 1) * limit
    
    for i in range(limit):
        item_idx = (base_index + i) % len(candidates)
        bp = candidates[item_idx]
        cycle = (base_index + i) // len(candidates) + 1
        plat = platforms[(base_index + i) % len(platforms)]
        
        item_id = f"inf_{plat}_{item_idx}_{cycle}"
        title = f"{bp['topic']} #{cycle}" if cycle > 1 else bp["topic"]
        q_enc = urllib.parse.quote_plus(bp["query"])
        
        if plat == "facebook":
            channel = bp.get("channel_fb", "Facebook Watch")
            url = f"https://www.facebook.com/watch/search/?q={q_enc}"
            duration = f"{10 + (item_idx * 3) % 25}:00"
            match_reason = f"f Trending on Facebook Watch for {bp['decades'][0]} lovers"
        elif plat == "x":
            channel = bp.get("channel_x", "Archive on 𝕏")
            url = f"https://x.com/search?q={q_enc}&f=video"
            duration = f"{3 + (item_idx * 2) % 8}:{15 + (item_idx * 7) % 45:02d}"
            match_reason = f"𝕏 Archival Clip from {bp['decades'][0]} memories"
        else:
            channel = bp.get("channel_yt", "YouTube Classics")
            url = f"https://www.youtube.com/results?search_query={q_enc}"
            duration = f"{4 + (item_idx * 2) % 15}:{10 + (item_idx * 5) % 50:02d}"
            match_reason = f"▶ Curated YouTube recommendation from {bp['decades'][0]}"

        results.append({
            "id": item_id,
            "platform": plat,
            "title": title,
            "channel": channel,
            "thumbnail": bp["thumbnail"],
            "url": url,
            "embed_url": "",
            "duration": duration,
            "categories": [bp["category"]],
            "decades": bp["decades"],
            "languages": ["Hindi"],
            "culture_tags": bp["culture_tags"],
            "description": f"Curated {plat.title()} stream: {bp['topic']}. Handpicked for senior wellness and nostalgia.",
            "matchReason": match_reason,
            "is_infinite_stream": True
        })
        
    return results

